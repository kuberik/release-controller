#!/usr/bin/env python3
"""Generate example ReleaseSources and Rollout patch snippets from a parity baseline.

  hack/gen-examples/gen.py <baseline.json> <out-dir>

For every Rollout in the baseline: one ReleaseSource in the Rollout's namespace
named after its ImagePolicy (spec.releasesImagePolicy.name), pointing at that
ImagePolicy, with retention copied from availableReleasesRetentionDays/MinCount
(omitted when unset, so the CRD defaults of 7/30 apply). Rollouts sharing an
ImagePolicy name in one namespace share one ReleaseSource.

Writes <out-dir>/releasesources.yaml, <out-dir>/rollout-patches.yaml (snippets,
NOT in the kustomization: they patch Rollouts Flux owns) and kustomization.yaml.
Output is deterministic (sorted).
"""
import json, os, sys

HEADER = "# Generated by hack/gen-examples/gen.py from {src}. Do not edit by hand.\n"


def main(src, out):
    items = json.load(open(src))["items"]
    rollouts = sorted((i for i in items if i["kind"] == "Rollout"),
                      key=lambda r: (r["metadata"]["namespace"], r["metadata"]["name"]))
    sources, patches, seen = [], [], set()
    for r in rollouts:
        ns, name, spec = r["metadata"]["namespace"], r["metadata"]["name"], r["spec"]
        pol = (spec.get("releasesImagePolicy") or {}).get("name")
        if not pol:
            sys.exit(f"{ns}/{name}: no releasesImagePolicy")
        if (ns, pol) not in seen:
            seen.add((ns, pol))
            ret = []
            if "availableReleasesRetentionDays" in spec:
                ret.append(f"    days: {spec['availableReleasesRetentionDays']}")
            if "availableReleasesMinCount" in spec:
                ret.append(f"    minCount: {spec['availableReleasesMinCount']}")
            s = (f"apiVersion: kuberik.com/v1alpha1\nkind: ReleaseSource\nmetadata:\n"
                 f"  name: {pol}\n  namespace: {ns}\nspec:\n  oci:\n"
                 f"    imagePolicyRef: {{name: {pol}}}\n")
            if ret:
                s += "  retention:\n" + "\n".join(ret) + "\n"
            sources.append(s)
        patches.append(f"apiVersion: kuberik.com/v1alpha1\nkind: Rollout\nmetadata:\n"
                       f"  name: {name}\n  namespace: {ns}\nspec:\n"
                       f"  releaseSourceRef: {{name: {pol}}}\n")
    os.makedirs(out, exist_ok=True)
    h = HEADER.format(src=os.path.basename(src))
    open(f"{out}/releasesources.yaml", "w").write(h + "---\n".join(sources))
    open(f"{out}/rollout-patches.yaml", "w").write(
        h + "# Apply in Git (Flux owns the Rollouts) after the ReleaseSources are Ready.\n" + "---\n".join(patches))
    open(f"{out}/kustomization.yaml", "w").write(
        "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n- releasesources.yaml\n")
    print(f"{out}: {len(sources)} ReleaseSources, {len(patches)} Rollout patches")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
